#!/usr/bin/env python3
"""Generate the vector encoding table used by Kites.

Reads the machine-readable encodings published by riscv-opcodes
(https://github.com/riscv/riscv-opcodes, files extensions/rv_v, rv_zvbb and
rv_zvbc) and writes src/processor/vector/vector_isa_table.inc, one entry per
instruction:

    KITES_RVV_INSN("vadd.vv", 0x00000057u, 0xfc00707fu, kVm | kVs2 | kVs1 | kVd, kExtV)

`match` holds the fixed bits, `mask` marks which bits are fixed, the fourth
argument lists the variable operand fields and the last one names the
extension that defines the instruction. Zvkb is the subset of Zvbb listed in
ZVKB below (riscv-opcodes rv_zvkn imports exactly these from rv_zvbb).

Usage:
    python3 -I tools/vector/gen_vector_isa.py <output.inc> <commit> <rv_v> [<rv_zvbb> <rv_zvbc>]
"""

import os
import sys

# Bit ranges of the variable fields that appear in rv_v (from riscv-opcodes arg_lut.csv).
FIELDS = {
    "vd": (11, 7), "vs3": (11, 7), "rd": (11, 7),
    "vs1": (19, 15), "rs1": (19, 15), "simm5": (19, 15), "zimm5": (19, 15),
    "vs2": (24, 20), "rs2": (24, 20),
    "vm": (25, 25), "nf": (31, 29),
    "zimm10": (29, 20), "zimm11": (30, 20),
    "zimm6hi": (26, 26), "zimm6lo": (19, 15),  # vror.vi: uimm6 split over bits 26 and 19..15
}
CPP_NAME = {
    "vd": "kVd", "vs3": "kVs3", "rd": "kRd", "vs1": "kVs1", "rs1": "kRs1",
    "simm5": "kSimm5", "zimm5": "kZimm5", "vs2": "kVs2", "rs2": "kRs2",
    "vm": "kVm", "nf": "kNf", "zimm10": "kZimm10", "zimm11": "kZimm11",
    "zimm6hi": "kZimm6", "zimm6lo": "kZimm6",
}
EXTENSION = {"rv_v": "kExtV", "rv_zvbb": "kExtZvbb", "rv_zvbc": "kExtZvbc"}
ZVKB = {"vandn.vv", "vandn.vx", "vbrev8.v", "vrev8.v", "vrol.vv", "vrol.vx", "vror.vv",
        "vror.vx", "vror.vi"}


def bits(hi, lo):
    return ((1 << (hi - lo + 1)) - 1) << lo


def parse_line(line):
    tokens = line.split()
    name, specs = tokens[0], tokens[1:]
    match = mask = 0
    fields = []
    for spec in specs:
        if "=" in spec:
            lhs, value = spec.split("=")
            value = int(value, 0)
            if lhs in FIELDS:
                hi, lo = FIELDS[lhs]
            elif ".." in lhs:
                hi, lo = (int(x) for x in lhs.split(".."))
            else:
                hi = lo = int(lhs)
            field_mask = bits(hi, lo)
            if value << lo & ~field_mask:
                raise ValueError(f"{name}: value {value} does not fit {lhs}")
            if mask & field_mask:
                raise ValueError(f"{name}: overlapping fixed bits in {spec}")
            mask |= field_mask
            match |= value << lo
        else:
            if spec not in FIELDS:
                raise ValueError(f"{name}: unknown field {spec}")
            fields.append(spec)
    variable = 0
    for f in fields:
        variable |= bits(*FIELDS[f])
    if (mask | variable) != 0xFFFFFFFF or mask & variable:
        raise ValueError(f"{name}: fields do not cover all 32 bits exactly")
    return name, match, mask, fields


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    out, commit, sources = sys.argv[1], sys.argv[2], sys.argv[3:]
    entries = []
    for src in sources:
        ext = EXTENSION[os.path.basename(src)]
        with open(src) as f:
            for raw in f:
                line = raw.split("#")[0].strip()
                if not line or line.startswith("$"):
                    continue
                name, match, mask, fields = parse_line(line)
                tag = "kExtZvkb" if ext == "kExtZvbb" and name in ZVKB else ext
                entries.append((name, match, mask, fields, tag))
    names = [e[0] for e in entries]
    if len(names) != len(set(names)):
        sys.exit("duplicate mnemonics in input")
    for i, a in enumerate(entries):  # no word may match two entries
        for b in entries[i + 1:]:
            common = a[2] & b[2]
            if (a[1] & common) == (b[1] & common):
                sys.exit(f"{a[0]} and {b[0]} overlap")

    with open(out, "w") as f:
        f.write("// Generated by tools/vector/gen_vector_isa.py from riscv-opcodes extensions/"
                + ", ".join(os.path.basename(s) for s in sources) + ".\n")
        f.write(f"// riscv-opcodes commit: {commit}\n")
        f.write(f"// {len(entries)} instructions. Do not edit by hand.\n")
        f.write("// clang-format off\n")
        for name, match, mask, fields, tag in entries:
            cpp = []
            for x in fields:
                if CPP_NAME[x] not in cpp:
                    cpp.append(CPP_NAME[x])
            field_expr = " | ".join(cpp) or "0u"
            f.write(f'KITES_RVV_INSN("{name}", 0x{match:08x}u, 0x{mask:08x}u, {field_expr}, {tag})\n')
        f.write("// clang-format on\n")
    print(f"wrote {len(entries)} entries to {out}")


if __name__ == "__main__":
    main()
