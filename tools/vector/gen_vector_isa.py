#!/usr/bin/env python3
"""Generate the RVV 1.0 encoding table used by Kites.

Reads the machine-readable vector encodings published by riscv-opcodes
(https://github.com/riscv/riscv-opcodes, file extensions/rv_v) and writes
src/processor/vector/vector_isa_table.inc, one entry per instruction:

    KITES_RVV_INSN("vadd.vv", 0x00000057u, 0xfc00707fu, kVm | kVs2 | kVs1 | kVd)

`match` holds the fixed bits, `mask` marks which bits are fixed, and the last
argument lists the variable operand fields.

Usage:
    python3 -I tools/vector/gen_vector_isa.py <rv_v> <output.inc> [<riscv-opcodes commit>]
"""

import sys

# Bit ranges of the variable fields that appear in rv_v (from riscv-opcodes arg_lut.csv).
FIELDS = {
    "vd": (11, 7), "vs3": (11, 7), "rd": (11, 7),
    "vs1": (19, 15), "rs1": (19, 15), "simm5": (19, 15), "zimm5": (19, 15),
    "vs2": (24, 20), "rs2": (24, 20),
    "vm": (25, 25), "nf": (31, 29),
    "zimm10": (29, 20), "zimm11": (30, 20),
}
CPP_NAME = {
    "vd": "kVd", "vs3": "kVs3", "rd": "kRd", "vs1": "kVs1", "rs1": "kRs1",
    "simm5": "kSimm5", "zimm5": "kZimm5", "vs2": "kVs2", "rs2": "kRs2",
    "vm": "kVm", "nf": "kNf", "zimm10": "kZimm10", "zimm11": "kZimm11",
}


def bits(hi, lo):
    return ((1 << (hi - lo + 1)) - 1) << lo


def parse_line(line):
    tokens = line.split()
    name, specs = tokens[0], tokens[1:]
    match = mask = 0
    fields = []
    for spec in specs:
        if "=" in spec:
            lhs, value = spec.split("=")
            value = int(value, 0)
            if lhs in FIELDS:
                hi, lo = FIELDS[lhs]
            elif ".." in lhs:
                hi, lo = (int(x) for x in lhs.split(".."))
            else:
                hi = lo = int(lhs)
            field_mask = bits(hi, lo)
            if value << lo & ~field_mask:
                raise ValueError(f"{name}: value {value} does not fit {lhs}")
            if mask & field_mask:
                raise ValueError(f"{name}: overlapping fixed bits in {spec}")
            mask |= field_mask
            match |= value << lo
        else:
            if spec not in FIELDS:
                raise ValueError(f"{name}: unknown field {spec}")
            fields.append(spec)
    variable = 0
    for f in fields:
        variable |= bits(*FIELDS[f])
    if (mask | variable) != 0xFFFFFFFF or mask & variable:
        raise ValueError(f"{name}: fields do not cover all 32 bits exactly")
    return name, match, mask, fields


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    commit = sys.argv[3] if len(sys.argv) == 4 else "unknown"
    entries = []
    with open(src) as f:
        for raw in f:
            line = raw.split("#")[0].strip()
            if not line or line.startswith("$"):
                continue
            entries.append(parse_line(line))
    names = [e[0] for e in entries]
    if len(names) != len(set(names)):
        sys.exit("duplicate mnemonics in input")

    with open(out, "w") as f:
        f.write("// Generated by tools/vector/gen_vector_isa.py from riscv-opcodes extensions/rv_v.\n")
        f.write(f"// riscv-opcodes commit: {commit}\n")
        f.write(f"// {len(entries)} instructions. Do not edit by hand.\n")
        f.write("// clang-format off\n")
        for name, match, mask, fields in entries:
            field_expr = " | ".join(CPP_NAME[x] for x in fields) or "0u"
            f.write(f'KITES_RVV_INSN("{name}", 0x{match:08x}u, 0x{mask:08x}u, {field_expr})\n')
        f.write("// clang-format on\n")
    print(f"wrote {len(entries)} entries to {out}")


if __name__ == "__main__":
    main()
